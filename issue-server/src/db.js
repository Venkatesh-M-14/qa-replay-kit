import Database from 'better-sqlite3';
import { createHash } from 'node:crypto';
import { mkdirSync } from 'node:fs';
import path from 'node:path';

// viewport width buckets used to compare like with like on heatmaps
export const DEVICES = {
  desktop: 'viewport_w >= 1024',
  tablet: 'viewport_w >= 768 AND viewport_w < 1024',
  mobile: 'viewport_w < 768',
};

export function openDb(dataDir) {
  mkdirSync(dataDir, { recursive: true });
  const db = new Database(path.join(dataDir, 'issues.db'));
  db.pragma('journal_mode = WAL');
  db.pragma('foreign_keys = ON');
  db.exec(`
    CREATE TABLE IF NOT EXISTS sessions (
      id              TEXT PRIMARY KEY,
      name            TEXT NOT NULL,
      url             TEXT,
      user_agent      TEXT,
      recorded_at     INTEGER NOT NULL,
      duration_ms     INTEGER NOT NULL,
      steps_count     INTEGER NOT NULL,
      console_errors  INTEGER NOT NULL,
      failed_requests INTEGER NOT NULL,
      issues_count    INTEGER NOT NULL,
      created_at      INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS issues (
      id          INTEGER PRIMARY KEY AUTOINCREMENT,
      session_id  TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
      offset_ms   INTEGER NOT NULL,
      source      TEXT NOT NULL,          -- 'console' | 'network'
      title       TEXT NOT NULL,
      detail      TEXT,
      trigger     TEXT,                   -- last user action before the issue
      fingerprint TEXT NOT NULL,          -- groups the same issue across sessions
      created_at  INTEGER NOT NULL,
      occurrences INTEGER NOT NULL DEFAULT 1, -- repeats within the session
      severity    TEXT NOT NULL DEFAULT 'error' -- 'error' | 'warning'
    );
    CREATE INDEX IF NOT EXISTS issues_session ON issues(session_id);
    CREATE INDEX IF NOT EXISTS issues_fingerprint ON issues(fingerprint);

    -- one row per click, for click heatmaps
    CREATE TABLE IF NOT EXISTS clicks (
      id          INTEGER PRIMARY KEY AUTOINCREMENT,
      session_id  TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
      page        TEXT NOT NULL,          -- path without query string
      offset_ms   INTEGER NOT NULL,
      x           INTEGER NOT NULL,       -- viewport position
      y           INTEGER NOT NULL,
      page_y      INTEGER NOT NULL,       -- position in the scrolled page
      x_ratio     REAL NOT NULL,          -- x / viewport width
      viewport_w  INTEGER NOT NULL,
      viewport_h  INTEGER NOT NULL,
      element     TEXT NOT NULL,          -- e.g. button#buy "Place order"
      recorded_at INTEGER NOT NULL
    );
    CREATE INDEX IF NOT EXISTS clicks_page ON clicks(page, recorded_at);
    CREATE INDEX IF NOT EXISTS clicks_session ON clicks(session_id);

    -- one row per visit to a page, for scroll-depth heatmaps
    CREATE TABLE IF NOT EXISTS page_views (
      id          INTEGER PRIMARY KEY AUTOINCREMENT,
      session_id  TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
      page        TEXT NOT NULL,
      offset_ms   INTEGER NOT NULL,
      viewport_w  INTEGER NOT NULL,
      max_depth   INTEGER NOT NULL,       -- deepest pixel that was on screen
      page_height INTEGER,                -- NULL when the recording has no page metrics
      container   INTEGER NOT NULL DEFAULT 0,
      recorded_at INTEGER NOT NULL
    );
    CREATE INDEX IF NOT EXISTS page_views_page ON page_views(page, recorded_at);
    CREATE INDEX IF NOT EXISTS page_views_session ON page_views(session_id);

    CREATE TABLE IF NOT EXISTS feedback (
      id          TEXT PRIMARY KEY,       -- generated by the extension; makes retries idempotent
      created_at  INTEGER NOT NULL,
      updated_at  INTEGER NOT NULL,
      category    TEXT NOT NULL,
      rating      INTEGER,                -- 1-5, NULL when not given
      comment     TEXT NOT NULL DEFAULT '',
      contact     TEXT NOT NULL DEFAULT '',
      page_url    TEXT NOT NULL DEFAULT '', -- without query string
      page        TEXT NOT NULL DEFAULT '',
      page_title  TEXT NOT NULL DEFAULT '',
      viewport_w  INTEGER,
      viewport_h  INTEGER,
      user_agent  TEXT NOT NULL DEFAULT '',
      screenshot  TEXT,                   -- file name in data/feedback
      recording   INTEGER NOT NULL DEFAULT 0,
      session_id  TEXT REFERENCES sessions(id) ON DELETE SET NULL,
      offset_ms   INTEGER,
      status      TEXT NOT NULL DEFAULT 'new',
      notes       TEXT NOT NULL DEFAULT ''
    );
    CREATE INDEX IF NOT EXISTS feedback_created ON feedback(created_at);

    CREATE TABLE IF NOT EXISTS settings (
      key   TEXT PRIMARY KEY,
      value TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS feedback_session ON feedback(session_id);
  `);
  // databases created before occurrences/severity existed
  const columns = db
    .prepare('PRAGMA table_info(issues)')
    .all()
    .map((c) => c.name);
  if (!columns.includes('occurrences'))
    db.exec(
      'ALTER TABLE issues ADD COLUMN occurrences INTEGER NOT NULL DEFAULT 1',
    );
  if (!columns.includes('severity'))
    db.exec(
      "ALTER TABLE issues ADD COLUMN severity TEXT NOT NULL DEFAULT 'error'",
    );
  // React development warnings saved by older extension builds were stored as errors
  db.exec(`
    UPDATE issues SET severity = 'warning'
    WHERE severity = 'error' AND source = 'console' AND (
      title LIKE 'In HTML, %' OR title LIKE 'Warning: %' OR title LIKE '<!%s>%' ESCAPE '!'
      OR title LIKE '%validateDOMNesting%' OR title LIKE 'Each child in a list should have a unique%');
    UPDATE sessions SET issues_count = (
      SELECT COUNT(*) FROM issues WHERE issues.session_id = sessions.id AND severity = 'error');
  `);
  return db;
}

/**
 * Strips the parts of an issue title that change between runs (ports, ids,
 * numbers, query strings) so repeated occurrences of one bug share a fingerprint.
 */
export function fingerprint(source, title) {
  const normalized = title
    .replace(/https?:\/\/[^/\s]+/g, '')
    .replace(/\?[^\s]*/g, '')
    .replace(/[0-9a-f]{8,}/gi, ':id')
    .replace(/\d+/g, ':n')
    .toLowerCase();
  return createHash('sha1')
    .update(`${source}|${normalized}`)
    .digest('hex')
    .slice(0, 12);
}

/** Date-range condition on a timestamp column; from/to are epoch ms or undefined. */
function range(column, { from, to }, params) {
  const parts = [];
  if (from !== undefined) {
    parts.push(`${column} >= @from`);
    params.from = from;
  }
  if (to !== undefined) {
    parts.push(`${column} < @to`);
    params.to = to;
  }
  return parts;
}

const where = (parts) => (parts.length ? `WHERE ${parts.join(' AND ')}` : '');

export function insertSession(
  db,
  row,
  { issues, clicks, pageViews, feedback },
) {
  const upsertSession = db.prepare(`
    INSERT INTO sessions
      (id, name, url, user_agent, recorded_at, duration_ms, steps_count,
       console_errors, failed_requests, issues_count, created_at)
    VALUES
      (@id, @name, @url, @user_agent, @recorded_at, @duration_ms, @steps_count,
       @console_errors, @failed_requests, @issues_count, @created_at)
    ON CONFLICT(id) DO UPDATE SET
      name = excluded.name, url = excluded.url, user_agent = excluded.user_agent,
      recorded_at = excluded.recorded_at, duration_ms = excluded.duration_ms,
      steps_count = excluded.steps_count, console_errors = excluded.console_errors,
      failed_requests = excluded.failed_requests, issues_count = excluded.issues_count,
      created_at = excluded.created_at`);
  const deleteChildren = ['issues', 'clicks', 'page_views'].map((table) =>
    db.prepare(`DELETE FROM ${table} WHERE session_id = ?`),
  );
  const insertIssue = db.prepare(`
    INSERT INTO issues
      (session_id, offset_ms, source, title, detail, trigger, fingerprint,
       created_at, occurrences, severity)
    VALUES
      (@session_id, @offset_ms, @source, @title, @detail, @trigger, @fingerprint,
       @created_at, @occurrences, @severity)`);
  const insertClick = db.prepare(`
    INSERT INTO clicks
      (session_id, page, offset_ms, x, y, page_y, x_ratio, viewport_w,
       viewport_h, element, recorded_at)
    VALUES
      (@session_id, @page, @offset_ms, @x, @y, @page_y, @x_ratio, @viewport_w,
       @viewport_h, @element, @recorded_at)`);
  const insertView = db.prepare(`
    INSERT INTO page_views
      (session_id, page, offset_ms, viewport_w, max_depth, page_height,
       container, recorded_at)
    VALUES
      (@session_id, @page, @offset_ms, @viewport_w, @max_depth, @page_height,
       @container, @recorded_at)`);
  const linkFeedback = db.prepare(
    'UPDATE feedback SET session_id = @session_id, offset_ms = @offset_ms WHERE id = @id',
  );
  db.transaction(() => {
    upsertSession.run(row);
    // re-saving a session replaces its rows instead of duplicating them
    for (const stmt of deleteChildren) stmt.run(row.id);
    for (const issue of issues) insertIssue.run(issue);
    for (const click of clicks) insertClick.run(click);
    for (const view of pageViews) insertView.run(view);
    for (const link of feedback) linkFeedback.run(link);
  })();
}

export function listSessions(db, filters = {}) {
  const params = {};
  const parts = range('s.recorded_at', filters, params);
  if (filters.q) {
    parts.push('(s.name LIKE @q OR s.url LIKE @q)');
    params.q = `%${filters.q}%`;
  }
  if (filters.errors) parts.push('s.issues_count > 0');
  if (filters.page) {
    parts.push(
      'EXISTS (SELECT 1 FROM page_views v WHERE v.session_id = s.id AND v.page = @page)',
    );
    params.page = filters.page;
  }
  return db
    .prepare(
      `SELECT s.*,
         (SELECT COUNT(DISTINCT page) FROM page_views v WHERE v.session_id = s.id) AS pages,
         (SELECT COUNT(*) FROM feedback f WHERE f.session_id = s.id) AS feedback_count
       FROM sessions s ${where(parts)}
       ORDER BY s.recorded_at DESC LIMIT 500`,
    )
    .all(params);
}

