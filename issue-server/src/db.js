export function insertFeedback(db, row) {
  db.prepare(
    `INSERT INTO feedback
       (id, created_at, updated_at, category, rating, comment, contact, page_url,
        page, page_title, viewport_w, viewport_h, user_agent, screenshot, recording)
     VALUES
       (@id, @created_at, @created_at, @category, @rating, @comment, @contact, @page_url,
        @page, @page_title, @viewport_w, @viewport_h, @user_agent, @screenshot, @recording)`,
  ).run(row);
}

export function updateFeedback(db, id, { status, notes }) {
  db.prepare(
    `UPDATE feedback SET
       status = COALESCE(@status, status),
       notes = COALESCE(@notes, notes),
       updated_at = @now
     WHERE id = @id`,
  ).run({ id, status: status ?? null, notes: notes ?? null, now: Date.now() });
}

export function listFeedback(db, filters = {}) {
  const params = {};
  const parts = range('created_at', filters, params);
  for (const key of ['status', 'category', 'page']) {
    if (filters[key]) {
      parts.push(`${key} = @${key}`);
      params[key] = filters[key];
    }
  }
  if (filters.rating) {
    parts.push('rating = @rating');
    params.rating = Number(filters.rating);
  }
  if (filters.q) {
    parts.push('(comment LIKE @q OR page_title LIKE @q OR notes LIKE @q)');
    params.q = `%${filters.q}%`;
  }
  return db
    .prepare(
      `SELECT * FROM feedback ${where(
        parts,
      )} ORDER BY created_at DESC LIMIT 1000`,
    )
    .all(params);
}

// ---- heatmaps ----

function heatmapFilter(filters, params) {
  const parts = ['page = @page', ...range('recorded_at', filters, params)];
  params.page = filters.page;
  if (DEVICES[filters.device]) parts.push(DEVICES[filters.device]);
  return parts;
}

export function listHeatmapPages(db, filters = {}) {
  const params = {};
  const parts = range('recorded_at', filters, params);
  return db
    .prepare(
      `SELECT page, COUNT(*) AS clicks, COUNT(DISTINCT session_id) AS sessions
       FROM clicks ${where(parts)} GROUP BY page ORDER BY clicks DESC`,
    )
    .all(params);
}

export function heatmapClicks(db, filters) {
  const params = {};
  return db
    .prepare(
      `SELECT session_id, offset_ms, x, y, page_y, x_ratio, viewport_w, viewport_h, element
       FROM clicks ${where(heatmapFilter(filters, params))}
       ORDER BY recorded_at DESC LIMIT 20000`,
    )
    .all(params);
}

export function heatmapPageViews(db, filters) {
  const params = {};
  return db
    .prepare(
      `SELECT session_id, offset_ms, viewport_w, max_depth, page_height, container
       FROM page_views ${where(heatmapFilter(filters, params))}`,
    )
    .all(params);
}

