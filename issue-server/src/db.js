export function overviewStats(db, filters = {}) {
  const sessionParams = {};
  const sessionWhere = where(range('recorded_at', filters, sessionParams));
  const feedbackParams = {};
  const feedbackWhere = where(range('created_at', filters, feedbackParams));
  const sessions = db
    .prepare(
      `SELECT COUNT(*) AS total,
              COALESCE(SUM(issues_count > 0), 0) AS with_errors,
              COALESCE(SUM(duration_ms), 0) AS duration
       FROM sessions ${sessionWhere}`,
    )
    .get(sessionParams);
  const clicks = db
    .prepare(`SELECT COUNT(*) AS total FROM clicks ${sessionWhere}`)
    .get(sessionParams);
  const errors = db
    .prepare(
      `SELECT COALESCE(SUM(i.occurrences), 0) AS total
       FROM issues i JOIN sessions s ON s.id = i.session_id
       ${where([
         "i.severity = 'error'",
         ...range('s.recorded_at', filters, {}),
       ])}`,
    )
    .get(sessionParams);
  const scroll = db
    .prepare(
      `SELECT COUNT(*) AS views,
              AVG(MIN(1.0, CAST(max_depth AS REAL) / page_height)) AS average
       FROM page_views ${where([
         'page_height > 0',
         ...range('recorded_at', filters, {}),
       ])}`,
    )
    .get(sessionParams);
  const feedback = db
    .prepare(
      `SELECT COUNT(*) AS total, AVG(rating) AS average_rating,
              COUNT(rating) AS rated,
              COALESCE(SUM(status = 'new'), 0) AS unread
       FROM feedback ${feedbackWhere}`,
    )
    .get(feedbackParams);
  return { sessions, clicks, errors, scroll, feedback };
}

// ---- settings ----

/** Values shown in the Jira preview and used in the REST payload. */
export const JIRA_DEFAULTS = {
  projectKey: 'SHARESV',
  assignee: '',
  reporter: '',
  sprint: '',
};

export function getJiraSettings(db) {
  const rows = db
    .prepare("SELECT key, value FROM settings WHERE key LIKE 'jira.%'")
    .all();
  const stored = Object.fromEntries(rows.map((r) => [r.key.slice(5), r.value]));
  return { ...JIRA_DEFAULTS, ...stored };
}

export function saveJiraSettings(db, values) {
  const upsert = db.prepare(
    'INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value',
  );
  db.transaction(() => {
    for (const key of Object.keys(JIRA_DEFAULTS))
      if (typeof values[key] === 'string')
        upsert.run(`jira.${key}`, values[key].trim());
  })();
}
